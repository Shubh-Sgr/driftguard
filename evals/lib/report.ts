import type { LockCase } from "./lockAccuracy.js";
import type { BenchResult } from "./rewriteBench.js";
import type { ScenarioResult } from "./scenarios.js";

export interface EvalResults {
  runAt: string;
  environment: { node: string; platform: string; cpu: string; postgres: string; llm: string | null };
  scenarios?: ScenarioResult[];
  locks?: LockCase[];
  rewrite?: BenchResult[];
}

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((100 * n) / d).toFixed(1)}%`);
const sum = <T>(xs: T[], f: (x: T) => number) => xs.reduce((a, x) => a + f(x), 0);
const ms = (n: number) => (n >= 1000 ? `${(n / 1000).toFixed(2)} s` : `${n} ms`);

/** Headline numbers, computed once so the markdown and JSON can't disagree. */
export function summarize(r: EvalResults) {
  const s = r.scenarios ?? [];
  const tp = sum(s, (x) => x.drift.tp);
  const fp = sum(s, (x) => x.drift.fp);
  const fn = sum(s, (x) => x.drift.fn);
  const data = s.filter((x) => x.data).map((x) => x.data!);
  const rules = s.filter((x) => x.rulesPlan).map((x) => x.rulesPlan!);
  const llm = s.filter((x) => x.llmPlan).map((x) => x.llmPlan!);
  const locks = r.locks ?? [];
  const rewriteMeasured = locks.filter((l) => l.measuredRewrite !== null && !l.error);
  return {
    scenarios: s.length,
    driftPrecision: pct(tp, tp + fp),
    driftRecall: pct(tp, tp + fn),
    driftCounts: { tp, fp, fn },
    dataTables: { tp: sum(data, (d) => d.tablesTp), fp: sum(data, (d) => d.tablesFp), fn: sum(data, (d) => d.tablesFn) },
    rowRecall: pct(sum(data, (d) => d.rowsFound), sum(data, (d) => d.rowsExpected)),
    rowsFalse: sum(data, (d) => d.rowsFalse),
    rowsFetched: sum(data, (d) => d.rowsFetched),
    rowsInMismatchedTables: sum(data, (d) => d.rowsInMismatchedTables),
    rulesShadowPass: `${rules.filter((p) => p.shadow === "pass").length}/${rules.length}`,
    llmValidFirstTry: llm.length ? pct(llm.filter((p) => p.attempts[0]?.valid).length, llm.length) : null,
    llmValidAfterRetry: llm.length ? pct(llm.filter((p) => p.author === "llm").length, llm.length) : null,
    llmFallback: llm.length ? pct(llm.filter((p) => p.fellBack).length, llm.length) : null,
    llmShadowPass: llm.length ? `${llm.filter((p) => p.shadow === "pass").length}/${llm.filter((p) => p.author === "llm").length}` : null,
    lockModeAccuracy: `${locks.filter((l) => l.modeCorrect).length}/${locks.length} (${pct(locks.filter((l) => l.modeCorrect).length, locks.length)})`,
    rewriteAccuracy: `${rewriteMeasured.filter((l) => l.measuredRewrite === l.predictedRewrite).length}/${rewriteMeasured.length} (${pct(rewriteMeasured.filter((l) => l.measuredRewrite === l.predictedRewrite).length, rewriteMeasured.length)})`,
  };
}

export function toMarkdown(r: EvalResults): string {
  const h = summarize(r);
  const L: string[] = [];
  L.push("# DriftGuard eval results", "");
  L.push(`Generated by \`npm run eval\` on ${r.runAt}. Every number below was measured by running the code; nothing is hand-entered.`, "");
  L.push(`Environment: Node ${r.environment.node}, ${r.environment.platform}, ${r.environment.cpu}, PostgreSQL ${r.environment.postgres}${r.environment.llm ? `, LLM ${r.environment.llm}` : ""}.`, "");

  L.push("## Summary", "", "| Metric | Result |", "|---|---|");
  if (r.scenarios) {
    L.push(`| Seeded scenarios | ${h.scenarios} |`);
    L.push(`| Drift detection precision / recall | ${h.driftPrecision} / ${h.driftRecall} (TP ${h.driftCounts.tp}, FP ${h.driftCounts.fp}, FN ${h.driftCounts.fn}) |`);
    L.push(`| Data mismatch detection (tables) | TP ${h.dataTables.tp}, FP ${h.dataTables.fp}, FN ${h.dataTables.fn} |`);
    L.push(`| Exact differing rows found by bisection | ${h.rowRecall} recall, ${h.rowsFalse} false rows |`);
    L.push(`| Rows fetched by bisection vs rows in mismatched tables | ${h.rowsFetched.toLocaleString("en-US")} vs ${h.rowsInMismatchedTables.toLocaleString("en-US")} |`);
    L.push(`| Rules-only plans verified by shadow run | ${h.rulesShadowPass} |`);
    if (h.llmValidFirstTry) {
      L.push(`| LLM plans valid on first try | ${h.llmValidFirstTry} |`);
      L.push(`| LLM plans valid after one retry | ${h.llmValidAfterRetry} |`);
      L.push(`| Fell back to rules-only plan | ${h.llmFallback} |`);
      L.push(`| Accepted LLM plans that pass the shadow run | ${h.llmShadowPass} |`);
    }
  }
  if (r.locks) {
    L.push(`| Lock mode predicted = lock measured in pg_locks | ${h.lockModeAccuracy} |`);
    L.push(`| Table rewrite predicted = relfilenode change measured | ${h.rewriteAccuracy} |`);
  }
  L.push("");

  if (r.rewrite) {
    L.push("## Safe rewrites under load", "");
    L.push("Each migration ran on a fresh copy of the seeded database while a probe queried the table every ~10 ms. *Max stall* is the slowest probe query: how long the application was blocked.", "");
    L.push("| Migration | Original: max stall | Original: duration | Rewritten: max stall | Rewritten: duration | Rewritten steps run |", "|---|---|---|---|---|---|");
    for (const b of r.rewrite) {
      const cell = (x: typeof b.original) => (x.ok ? ms(x.maxStallMs) : `failed: ${x.error}`);
      L.push(`| ${b.name} | ${cell(b.original)} | ${ms(b.original.durationMs)} | ${cell(b.rewritten)} | ${ms(b.rewritten.durationMs)} | ${b.rewrittenSteps}${b.manualStepsSkipped ? ` (+${b.manualStepsSkipped} manual)` : ""} |`);
    }
    L.push("");
  }

  if (r.scenarios) {
    L.push("## Scenarios", "", "| Scenario | Drift TP/FP/FN | Data | Rules plan (shadow) | LLM plan |", "|---|---|---|---|---|");
    for (const s of r.scenarios) {
      const data = s.data ? `rows ${s.data.rowsFound}/${s.data.rowsExpected}, fetched ${s.data.rowsFetched}, ${ms(s.data.verifyMs)}` : "";
      const llm = s.llmPlan ? `${s.llmPlan.author === "llm" ? `accepted (attempt ${s.llmPlan.attempts.length}), shadow ${s.llmPlan.shadow}` : "rejected → fallback"}` : "";
      L.push(`| ${s.name}: ${s.description} | ${s.drift.tp}/${s.drift.fp}/${s.drift.fn} | ${data} | ${s.rulesPlan ? `${s.rulesPlan.steps} steps, ${s.rulesPlan.shadow}` : ""} | ${llm} |`);
    }
    L.push("");
    const failures = r.scenarios.flatMap((s) => [
      ...s.drift.falsePositives.map((k) => `- ${s.name}: false positive \`${k}\``),
      ...s.drift.missed.map((k) => `- ${s.name}: missed \`${k}\``),
      ...(s.rulesPlan?.shadowFailure ? [`- ${s.name}: rules plan shadow failure: ${s.rulesPlan.shadowFailure}`] : []),
      ...(s.llmPlan?.shadowFailure ? [`- ${s.name}: LLM plan shadow failure: ${s.llmPlan.shadowFailure}`] : []),
    ]);
    if (failures.length) L.push("### Misses and failures", "", ...failures, "");
  }

  if (r.locks) {
    L.push("## Lock predictions vs measurements", "", "| Statement | Predicted | Measured | Rewrite predicted / measured |", "|---|---|---|---|");
    for (const l of r.locks) {
      const mark = l.modeCorrect ? "" : " ✗";
      L.push(`| \`${l.sql}\` | ${l.predictedMode ?? "none"} | ${l.error ? `error: ${l.error}` : `${l.measuredMode ?? "none"}${mark}`} | ${l.predictedRewrite ? "yes" : "no"} / ${l.measuredRewrite === null ? "n/a" : l.measuredRewrite ? "yes" : "no"}${l.measuredRewrite !== null && l.measuredRewrite !== l.predictedRewrite ? " ✗" : ""} |`);
    }
    L.push("");
  }
  return L.join("\n");
}
